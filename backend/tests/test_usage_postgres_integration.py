"""真 PostgreSQL 上的用量库验证，默认跳过；只写并清理随机 schema。

守的是内存 SQLite 证明不了的那些：记录真的落进**独立库**、索引与唯一约束真的建在库上、
时刻列带时区且按 UTC 解释、业务库的迁移链看不到用量表。

运行规矩（见 ``docs/specs/0001-llm-usage-statistics.md`` 的「真 PostgreSQL 层」）：首次交付前
跑一次；之后改动碰到用量库相关的东西（表结构与迁移、采集器的落库路径）时重跑；其它需求的
回归不必跑。

它需要一个**独立的**连接串变量指向用量测试库——复用业务库那个变量是不行的，用量在另一个库。
它还会用只读方式读业务库（当前配置的 ``DATABASE_URL``），核对业务库里没有这张表。
"""

